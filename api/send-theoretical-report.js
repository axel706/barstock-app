const { Resend } = require('resend');
const { shell, badge, table, attachment, signoff } = require('../lib/email-shell');
const resend = new Resend(process.env.RESEND_API_KEY);

module.exports = async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "POST") return res.status(405).json({ ok: false, error: "Method not allowed" });

  try {
    const {
      to, cc, replyTo,
      locationName, weekStart,
      totalLoss, itemsAnalyzed, noSalesCount,
      senderName, senderEmail,
      pdfBase64, filename,
      // Consumption Match manda su propio informe por aqui. Vercel Hobby
      // permite doce funciones y hay once: una segunda casi identica
      // dejaria a la app sin margen. Si no viene, todo se comporta como
      // siempre.
      reportTitle,

      // La tabla del resumen, cuando el informe trae la suya. Consumption
      // Match manda el desglose por categoria en botellas; Usage no manda
      // nada y se queda con la tabla de metricas de siempre.
      summaryHead, summaryRows
    } = req.body || {};

    if (!to || !weekStart) {
      return res.status(400).json({ ok: false, error: "Missing required fields" });
    }

    const normalizeEmails = (val) => {
      if (!val) return [];
      const arr = Array.isArray(val) ? val : String(val).split(',');
      return arr.map(e => String(e).trim()).filter(Boolean);
    };

    const toList = normalizeEmails(to);
    const ccList = normalizeEmails(cc);
    const loc = locationName || 'BarStock';
    const fmt = v => '$' + (Number(v) || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    const escapeHtml = s => String(s || '').replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));

    const weekLabel = (() => {
      try {
        const d = new Date(weekStart + 'T12:00:00');
        return d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
      } catch(e) { return weekStart; }
    })();

    // Dos versiones del mismo texto y no es un descuido: el cuerpo se
    // monta a mano y necesita el escapado; el pie pasa por shell(), que
    // escapa por su cuenta, y darle el ya escapado imprimiria &amp;amp;.
    const titlePlain = reportTitle || 'Theoretical Usage Report';
    const title = escapeHtml(titlePlain);
    const subject = `${title} — Week of ${weekLabel} — ${escapeHtml(loc)}`;
    const safeFilename = filename || `theoretical_usage_${weekStart}.pdf`;

    const lossColor = Number(totalLoss) > 0 ? '#D85A30' : '#1D9E75';

    // ── Dos informes por el mismo tubo ────────────────────────────────
    //
    // Aquí llegan el informe de Usage y el de Consumption Match. Vercel
    // Hobby permite doce funciones y hay once: gastar la última en un
    // correo casi idéntico dejaría a la aplicación sin margen.
    //
    // Se distinguen por lo que traen. Si el cliente manda `summaryRows`,
    // esa es la tabla; si no, se arma la de métricas de siempre. El
    // servidor no sabe —ni necesita saber— cuál de los dos informes es,
    // ni si la copia es para dirección o para barra: quien decide qué
    // cifras se enseñan es quien pulsa Enviar, y ya lo ha decidido antes
    // de llamar aquí.
    const resumen = (Array.isArray(summaryRows) && summaryRows.length)
      ? table(
          Array.isArray(summaryHead) && summaryHead.length ? summaryHead : ['Category', 'Value'],
          summaryRows
        )
      : table(
          ['Metric', 'Value'],
          [
            ['Total Loss', { v: fmt(totalLoss), bold: true, color: lossColor }],
            ['Items analyzed', String(Number(itemsAnalyzed) || 0)],
            ['No sales data', String(Number(noSalesCount) || 0)]
          ]
        );

    const htmlBody = shell({
  right: loc,
  footer: titlePlain,
  body:
    badge('🔍', titlePlain, `Week of ${weekLabel}`, '#dcfce7') +
    resumen +
    (pdfBase64 ? attachment(safeFilename, 'Variance, losses and item-level breakdown') : '') +
    `<p style="margin:0 0 24px;font-size:15px;color:#374151;line-height:1.75">This is an automated report generated by <strong style="color:#0f172a">BarStock Pro</strong> on behalf of <strong style="color:#0f172a">${escapeHtml(loc)}</strong>. For questions, contact ${escapeHtml(senderName || 'your BarStock administrator')}.</p>` +
    signoff(senderName || loc)
});

    const msgPayload = {
      from: senderEmail && senderName
        ? `${senderName} <${senderEmail}>`
        : 'BarStock Pro <no-reply@barstockpro.com>',
      to: toList,
      subject,
      html: htmlBody,
    };
    if (ccList.length) msgPayload.cc = ccList;
    if (replyTo) msgPayload.reply_to = replyTo;
    if (pdfBase64) {
      msgPayload.attachments = [{
        filename: safeFilename,
        content: pdfBase64,
      }];
    }

    const result = await resend.emails.send(msgPayload);
    return res.status(200).json({ ok: true, id: result?.id });
  } catch (err) {
    console.error('[send-theoretical-report]', err);
    return res.status(500).json({ ok: false, error: String(err?.message || err) });
  }
};
